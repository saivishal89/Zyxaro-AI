import pptxgen from 'pptxgenjs';
import { Session, Note } from './types';

export function exportGlobalData(sessions: Session[], notes: Note[]) {
  const data = {
    sessions,
    notes,
    exportedAt: new Date().toISOString()
  };
  
  const blob = new Blob([JSON.stringify(data, null, 2)], { type: 'application/json' });
  const url = URL.createObjectURL(blob);
  
  const a = document.createElement('a');
  a.href = url;
  a.download = `zyxaro-export-${Date.now()}.json`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export function exportToDoc(content: string) {
  // Convert basic markdown to HTML for doc
  let htmlContent = content
    .replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/\n\n/g, '</p><p>')
    .replace(/\n/g, '<br/>')
    .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>');
    
  const fullHtml = `
    <html xmlns:o='urn:schemas-microsoft-com:office:office' xmlns:w='urn:schemas-microsoft-com:office:word' xmlns='http://www.w3.org/TR/REC-html40'>
    <head><meta charset='utf-8'><title>Export Document</title></head>
    <body style="font-family: Calibri, sans-serif; font-size: 11pt;">
      <p>${htmlContent}</p>
      <br/><hr/>
      <p style="color: #666; font-size: 9pt;">Generated by ZYXARO AI</p>
    </body>
    </html>
  `;
  
  const blob = new Blob(['\ufeff', fullHtml], { type: 'application/msword' });
  const url = URL.createObjectURL(blob);
  
  const a = document.createElement('a');
  a.href = url;
  a.download = `Zyxaro_Research_${Date.now()}.doc`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export async function exportToPpt(content: string) {
  const pptx = new pptxgen();
  
  // Master Slide Definition
  pptx.defineSlideMaster({
    title: 'MASTER_SLIDE',
    background: { color: '03081A' },
    objects: [
      { text: { text: 'ZYXARO AI Research', options: { x: 0.5, y: 5.0, w: '90%', fontSize: 10, color: '60A5FA' } } }
    ]
  });

  // Title Slide
  const titleSlide = pptx.addSlide({ masterName: 'MASTER_SLIDE' });
  titleSlide.addText('ZYXARO AI', { x: 1, y: 1.5, w: '80%', h: 1, fontSize: 36, color: 'E2E8F0', align: 'center', fontFace: 'Orbitron' });
  titleSlide.addText('Research Report', { x: 1, y: 2.5, w: '80%', h: 1, fontSize: 24, color: '60A5FA', align: 'center' });

  // Parse sections based on ## headers
  const sections = content.split('## ').filter(Boolean);
  
  for (let i = 0; i < Math.min(sections.length, 15); i++) {
    const section = sections[i];
    const lines = section.split('\n');
    const title = lines[0].trim();
    
    // get bullets
    const bullets = lines.slice(1).filter(l => l.trim().startsWith('-')).map(l => l.replace(/^- /, '').replace(/\*\*/g, '').trim());
    
    if (title || bullets.length > 0) {
      const slide = pptx.addSlide({ masterName: 'MASTER_SLIDE' });
      slide.addText(title || 'Research Findings', { x: 0.5, y: 0.5, w: '90%', h: 0.8, fontSize: 24, color: '60A5FA', fontFace: 'Orbitron' });
      
      if (bullets.length > 0) {
        slide.addText(bullets.map(b => ({ text: b, options: { bullet: true } })), {
          x: 0.5, y: 1.5, w: '90%', h: 3.5, fontSize: 16, color: 'E2E8F0', fontFace: 'Exo 2'
        });
      } else {
        const textContent = lines.slice(1).join('\n').replace(/\*\*/g, '').trim().substring(0, 500);
        slide.addText(textContent, { x: 0.5, y: 1.5, w: '90%', h: 3.5, fontSize: 16, color: 'E2E8F0', fontFace: 'Exo 2' });
      }
    }
  }

  // If no sections were found (no ## used), just dump content
  if (sections.length === 0) {
    const slide = pptx.addSlide({ masterName: 'MASTER_SLIDE' });
    slide.addText('Research Findings', { x: 0.5, y: 0.5, w: '90%', h: 0.8, fontSize: 24, color: '60A5FA', fontFace: 'Orbitron' });
    slide.addText(content.replace(/\*\*/g, '').substring(0, 800), { x: 0.5, y: 1.5, w: '90%', h: 3.5, fontSize: 14, color: 'E2E8F0', fontFace: 'Exo 2' });
  }

  await pptx.writeFile({ fileName: `Zyxaro_Presentation_${Date.now()}.pptx` });
}
